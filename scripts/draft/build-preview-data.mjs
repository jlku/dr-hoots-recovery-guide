// Builds preview/assets/guide-data.js for the full-length draft previews.
// Merges canonical sentences with narration word timings from both audio manifests.
// Read-only over content/ and assets/audio/; writes a single generated module.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = async (p) => JSON.parse(await readFile(path.join(projectRoot, p), "utf8"));

const canonical = await read("content/canonical/ci-phase0-v0.1.0.json");
const baseAudio = await read("assets/audio/manifest.json");
const draftAudio = await read("assets/audio/draft/manifest.json");

function wordsFromTimestamps(timestamps) {
  const chars = [];
  for (const chunk of timestamps ?? []) {
    const { characters = [], character_start_times_seconds: starts = [], character_end_times_seconds: ends = [] } = chunk;
    for (let i = 0; i < characters.length; i += 1) chars.push({ c: characters[i], s: starts[i], e: ends[i] });
  }
  const words = [];
  let current = null;
  for (const { c, s, e } of chars) {
    if (/\s/.test(c)) {
      if (current) words.push(current);
      current = null;
      continue;
    }
    if (!current) current = { w: c, s, e };
    else {
      current.w += c;
      current.e = e;
    }
  }
  if (current) words.push(current);
  return words;
}

const tracks = {};
for (const record of [...baseAudio.records, ...draftAudio.records]) {
  const words = wordsFromTimestamps(record.timestamps);
  tracks[record.id] = {
    file: record.file,
    text: record.text,
    status: record.status,
    sentenceIds: record.canonicalSentenceIds ?? [],
    duration: words.length ? words[words.length - 1].e : null,
    words
  };
}

const modules = {};
for (const module of canonical.modules) {
  modules[module.id] = {
    title: module.title,
    phase: module.phase,
    sentences: Object.fromEntries(module.canonical_sentences.map((s) => [s.id, s.text]))
  };
}

const payload = {
  artifact: { id: canonical.artifact.id, version: canonical.artifact.version, status: canonical.artifact.status },
  modules,
  tracks
};

const banner = "// Generated by scripts/draft/build-preview-data.mjs — do not edit by hand.\n";
const body = `export const GUIDE_DATA = ${JSON.stringify(payload, null, 1)};\n`;
await mkdir(path.join(projectRoot, "preview", "assets"), { recursive: true });
await writeFile(path.join(projectRoot, "preview", "assets", "guide-data.js"), banner + body);
const trackCount = Object.keys(tracks).length;
console.log(`Wrote preview/assets/guide-data.js (${trackCount} tracks).`);
